<script>
	// Hidden on screen, shown only under @media print (see app.css's
	// `.print-report` rules) — the browser's own print-to-PDF is a real,
	// dependency-free way to get an actual PDF from real result data,
	// without pulling in a client-side PDF-generation library.
	let { result = null, previewUrl = '', class: className = '' } = $props();
</script>

{#if result}
	<div class="print-report {className}">
		<h1>Scam Detector — Analysis Report</h1>
		<p class="meta">
			Generated {new Date(result.scanTimestamp ?? Date.now()).toLocaleString()} · model {result.modelVersion} · feature schema {result.featureSchemaVersion}
		</p>

		{#if previewUrl}
			<img src={previewUrl} alt="Analyzed screenshot" class="screenshot" />
		{/if}

		<table>
			<tbody>
				<tr><th>Status</th><td>{result.prediction.label === 'genuine' ? 'Safe' : 'Likely a scam'}</td></tr>
				{#if result.prediction.category}<tr><th>Category</th><td>{result.prediction.category}</td></tr>{/if}
				<tr><th>Confidence</th><td>{result.prediction.confidence}%</td></tr>
				<tr><th>Risk score</th><td>{result.prediction.riskScore} / 100 ({result.prediction.riskBand})</td></tr>
			</tbody>
		</table>

		{#if result.explanation?.reasons?.length > 0}
			<h2>Why</h2>
			<ul>
				{#each result.explanation.reasons as reason (reason.text)}
					<li>{reason.text}</li>
				{/each}
			</ul>
		{/if}

		{#if result.recommendations?.length > 0}
			<h2>Recommended actions</h2>
			<ul>
				{#each result.recommendations as action (action)}
					<li>{action}</li>
				{/each}
			</ul>
		{/if}

		{#if result.ocr?.text}
			<h2>Extracted text (OCR, {result.ocr.confidence}% confidence)</h2>
			<pre>{result.ocr.text}</pre>
		{/if}

		<p class="footer">Generated by a local, research-stage scam-detection tool — not a substitute for professional or legal advice.</p>
	</div>
{/if}

